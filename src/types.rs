use serde::{Deserialize, Serialize};

/// One persisted pane of the `/agents` split: which agent CLI it runs and —
/// once the pane completed a turn — WHICH ACP session to resume, so a
/// reopened session (or app) continues the SAME agent context instead of
/// forking a fresh one. Serialized untagged: `Name` is a bare JSON string,
/// byte-identical with the pre-binding histories; `Bound` is a small object
/// only newer writers emit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum AgentPaneRef {
    /// A freshly picked pane that never ran yet: just the agent name. The
    /// next turn creates a new session and the pane promotes to `Bound`.
    Name(String),
    /// A pane with a durable agent context: `session_id` is the ACP session
    /// id the pane resumes on its next dispatch (its independent instance —
    /// two Claude panes carry two distinct ids).
    Bound {
        agent: String,
        session_id: String,
        /// The worktree the pane is pinned to, when isolated. `#[serde(default)]`
        /// keeps the untagged enum backward compatible: histories written before
        /// worktrees load with `None` (the pane shares the session's cwd), and
        /// `skip_serializing_if` keeps un-worktree'd panes byte-identical with
        /// pre-feature writes.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        worktree: Option<crate::git::worktree::PaneWorktree>,
    },
}

impl AgentPaneRef {
    /// The agent CLI this pane runs.
    #[must_use]
    pub fn agent(&self) -> &str {
        match self {
            Self::Name(agent) => agent,
            Self::Bound { agent, .. } => agent,
        }
    }

    /// The bound ACP session id, when the pane already ran once.
    #[must_use]
    pub fn session_id(&self) -> Option<&str> {
        match self {
            Self::Name(_) => None,
            Self::Bound { session_id, .. } => Some(session_id),
        }
    }

    /// The worktree the pane is pinned to, when isolated. `None` for a
    /// fresh pane and for a bound pane written before worktrees existed
    /// (the `#[serde(default)]` field loads as `None` there).
    #[must_use]
    pub fn worktree(&self) -> Option<&crate::git::worktree::PaneWorktree> {
        match self {
            Self::Name(_) => None,
            Self::Bound { worktree, .. } => worktree.as_ref(),
        }
    }
}

/// Ergonomics for the common fresh-pick construction: a bare name becomes
/// an unbound `Name` pane (`"claude".into()`), so call sites read exactly
/// like the pre-binding string lists.
impl From<&str> for AgentPaneRef {
    fn from(agent: &str) -> Self {
        Self::Name(agent.to_string())
    }
}

/// One `/agents` pane the user HID (Backspace on the focused pane) but did
/// NOT delete: the pane's durable identity plus the position it occupied in
/// the visible pane list when it was hidden, so a later restore (Ctrl+Z)
/// puts it back where it was. Hiding only moves a pane ref out of
/// `Session::agents_panes` into `Session::agents_hidden` — the session file
/// keeps the pane, its bound agent session is never deleted.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HiddenPane {
    /// The hidden pane's identity (agent CLI + bound session when it ran).
    pub pane: AgentPaneRef,
    /// Index the pane occupied in the visible list when it was hidden. Used
    /// to re-insert it at (or as close as possible to) its old slot.
    #[serde(default)]
    pub index: usize,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Session {
    pub id: String,
    pub title: String,
    pub messages: Vec<Message>,
    /// Unix timestamp in milliseconds when the session was created.
    pub created_at: u64,
    /// Whether the title was generated by the LLM.
    pub title_generated: bool,
    /// Provider of the last model used in this session. Persisted by metadata
    /// deltas so the model is restored when the session is reopened.
    pub provider: Option<String>,
    /// The last model used in this session. Persisted by metadata deltas.
    pub model: Option<String>,
    /// Reasoning effort (`None` = model default) for the last model used in
    /// this session. Persisted by metadata deltas.
    pub reasoning: Option<String>,
    /// The `/agents` split-pane mode left OPEN on this session: `Some(panes)`
    /// carries the chosen pane set (cosh only when the user marked it) so
    /// reopening the session restores the mode with the SAME panes — and,
    /// for panes that already ran, the SAME agent sessions (`AgentPaneRef` is
    /// serialized untagged: a bare name is byte-identical with the
    /// pre-binding histories, so old sessions load as fresh `Name` panes).
    /// Persisted by metadata deltas; only the mode and bindings are durable —
    /// running turns never are.
    #[serde(default)]
    pub agents_panes: Option<Vec<crate::types::AgentPaneRef>>,
    /// Whether the `/agents` split-screen MODE itself was left open — the
    /// companion of `agents_panes`, which also persists while the mode is
    /// closed (a parked split keeps its pane set + bindings for a later
    /// re-entry, but only `true` here restores the SPLIT SCREEN). Persisted
    /// with the session's regular saves.
    #[serde(default)]
    pub agents_mode_open: bool,
    /// The `/agents` panes the user HID (Backspace on the focused pane) but
    /// did NOT delete: a LIFO stack, last entry = most recently hidden.
    /// Nothing is removed from the session history — hiding only moves a
    /// pane ref out of `agents_panes` into this stack; Ctrl+Z pops the last
    /// and re-inserts it at its recorded position. Persisted by metadata
    /// deltas alongside `agents_panes`.
    #[serde(default)]
    pub agents_hidden: Vec<HiddenPane>,
    /// Legacy display bookkeeping: message id → context-manager item ids.
    /// New history boundaries are recorded as explicit context deltas, so a
    /// display-only save cannot erase the semantic view identity. This field
    /// remains for compatibility with older histories and UI rendering; it is
    /// never model-facing data.
    #[serde(default)]
    pub ctx_ids: std::collections::HashMap<String, Vec<u64>>,
    /// The worktree binding of the MAIN agent (normal chat, no `/agents`
    /// split), from `/worktree add`. `None` while the main agent works in
    /// the session's startup cwd. The main agent is addressable by no pane
    /// id, so `agents_worktree` can never target it — this binding is
    /// reachable ONLY through the user's slash command. Persisted so a
    /// reopened session keeps its isolation; `exit` clears it, returning
    /// the main agent to `AppState::working_directory` (the process cwd,
    /// stored once at startup and never mutated, so it IS the original).
    #[serde(default)]
    pub main_agent_worktree: Option<crate::git::worktree::PaneWorktree>,
}

impl Session {
    /// Assign a unique, stable `tool_call_id` to every tool part that lacks
    /// one. The id is derived from the message id and part index, so it is
    /// deterministic across reloads (a restored session re-derives the same
    /// keys) and unique per part — two bash boxes in one session never share
    /// an expansion key.
    ///
    /// This is the identity backbone for per-tool-box UI state (expand/
    /// collapse, LSP-notes toggle, spinners): without it, legacy parts created
    /// before ids were assigned would all fall back to the same per-tool-type
    /// constant key and toggle together.
    pub fn ensure_tool_call_ids(&mut self) {
        for msg in &mut self.messages {
            for (pi, part) in msg.parts.iter_mut().enumerate() {
                if let Part::Tool(t) = part
                    && t.tool_call_id
                        .as_deref()
                        .is_none_or(|id| id.trim().is_empty())
                {
                    t.tool_call_id = Some(format!("tc-{}-{pi}", msg.id));
                }
            }
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Message {
    pub id: String,
    pub role: MessageRole,
    pub parts: Vec<Part>,
    pub created_at: u64,
    pub agent: Option<String>,
    pub model: Option<String>,
}

impl Message {
    /// Append a reasoning delta while keeping all reasoning contiguous and
    /// ordered before the visible answer. If the answer (a `Text` part) has
    /// already started streaming, the delta is folded back into the last
    /// `Reasoning` part that precedes it instead of spawning a new Thought
    /// block after the answer.
    pub fn push_reasoning(&mut self, text: &str) {
        if let Some(text_idx) = self.parts.iter().position(|p| matches!(p, Part::Text(_))) {
            match (0..text_idx)
                .rev()
                .find(|&i| matches!(self.parts[i], Part::Reasoning(_)))
            {
                Some(i) => {
                    if let Part::Reasoning(rp) = &mut self.parts[i] {
                        rp.text.push_str(text);
                    }
                }
                None => self.parts.insert(
                    text_idx,
                    Part::Reasoning(ReasoningPart {
                        text: text.to_string(),
                        collapsed: true,
                    }),
                ),
            }
        } else if matches!(self.parts.last(), Some(Part::Reasoning(_))) {
            if let Some(Part::Reasoning(rp)) = self.parts.last_mut() {
                rp.text.push_str(text);
            }
        } else {
            self.parts.push(Part::Reasoning(ReasoningPart {
                text: text.to_string(),
                collapsed: true,
            }));
        }
    }
}

