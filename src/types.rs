/// A context-compaction status line in the chat: the LLM "Summarizing" box.
/// Persisted with the session like any other part.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CompactionPart {
    /// Which compaction phase this line reports (always [`CompactionPhase::Llm`]).
    pub phase: CompactionPhase,
    /// Wall-clock unix millis when the phase started (persisted so a restored
    /// session can still show a coherent elapsed time).
    pub started_at: u64,
    /// Final elapsed millis when the phase finished; `None` while running.
    pub elapsed_ms: Option<u64>,
    /// The streamed text of the summarizer: the tokens accumulate here and the
    /// "Summarizing" box renders them (collapsed = bounded preview that
    /// visually scrolls up, expanded = full growing body).
    #[serde(default)]
    pub text: String,
}

/// The only context-compaction phase a [`CompactionPart`] reports: the LLM
/// compaction (the last-resort fallback, driven by the harness). The model call
/// can take seconds, so its line carries a live stopwatch.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum CompactionPhase {
    Llm,
}

/// A weights-install progress line in the chat ([`Part::Install`]): the
/// decision-model mirror download the agent loop runs on first use.
/// Persisted with the session like any other part, so a restored session
/// replays the line (finished bars stay visible in the transcript).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct InstallPart {
    /// The model's user-facing name (`Laya`, `Laya-Multilingual`, …) —
    /// the line addresses the model by it ("installing Laya ▓▓▓…").
    /// `default` keeps sessions persisted before this field loadable.
    #[serde(default)]
    pub model: String,
    /// Bytes received across every file of the install.
    pub bytes_done: u64,
    /// Total bytes announced so far (grows as further files start).
    pub bytes_total: u64,
    /// `Some(elapsed_ms)` when the install reached a terminal state —
    /// finished (verified) or failed; `None` while running. Mirrors
    /// [`CompactionPart::elapsed_ms`]: the terminal event freezes the line.
    pub elapsed_ms: Option<u64>,
    /// How the install ended. `None` while running; set together with
    /// `elapsed_ms` by the terminal event.
    pub failed: Option<bool>,
    /// Wall-clock unix millis when the line opened (persisted so a restored
    /// session still renders a coherent elapsed time).
    pub started_at: u64,
}

impl InstallPart {
    /// A fresh running install line.
    pub fn running() -> Self {
        Self {
            model: String::new(),
            bytes_done: 0,
            bytes_total: 0,
            elapsed_ms: None,
            failed: None,
            started_at: now_ms(),
        }
    }

    pub fn is_running(&self) -> bool {
        self.elapsed_ms.is_none()
    }
}

impl CompactionPart {
    /// A fresh running phase line (stopwatch active).
    pub fn running(phase: CompactionPhase) -> Self {
        Self {
            phase,
            started_at: now_ms(),
            elapsed_ms: None,
            text: String::new(),
        }
    }

    pub fn is_running(&self) -> bool {
        self.elapsed_ms.is_none()
    }
}

/// Current wall-clock time in unix milliseconds (used by the stopwatch).
pub fn now_ms() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as u64
}

/// What the agent is doing right now while its loop runs. Drives the
/// agent spinner's label: the equalizer pulse stays the same, the text
/// beside it reflects the current activity.
///
/// Derived directly from the harness events the TUI already consumes —
/// no extra state channel: `Reasoning` → [`AgentActivity::Pondering`],
/// a `ToolCall` → [`AgentActivity::for_tool`], a `Token` / loop start →
/// [`AgentActivity::Working`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AgentActivity {
    /// Default state: the model is streaming a response or between steps.
    Working,
    /// The model is emitting a reasoning block.
    Pondering,
    /// A web tool (`web_search`, `web_fetch`) is running.
    Searching,
    /// A recall tool (`recall_search`) is running.
    Recalling,
}

impl AgentActivity {
    /// Label shown next to the spinner pulse.
    pub const fn label(self) -> &'static str {
        match self {
            AgentActivity::Working => "working",
            AgentActivity::Pondering => "pondering",
            AgentActivity::Searching => "searching",
            AgentActivity::Recalling => "recalling",
        }
    }

    /// The activity induced by a running tool call. Unknown tools keep the
    /// generic working state.
    pub fn for_tool(tool: &str) -> Self {
        match tool {
            "web_search" | "web_fetch" => AgentActivity::Searching,
            "recall_search" => AgentActivity::Recalling,
            _ => AgentActivity::Working,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SessionStatus {
    Idle,
    Working,
    Retry {
        message: String,
        action: Option<serde_json::Value>,
    },
}

